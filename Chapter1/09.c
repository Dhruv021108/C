#include <stdio.h>

int main() {
    printf("Hello, World!\n"); // Newline
    printf("This is a tab:\tTabbed text\n"); // Tab
    printf("This is a backspace:\bText\n"); // Backspace
    printf("This is a single quote: \' \n"); // Single Quote
    printf("This is a double quote: \" \n"); // Double Quote
    printf("This is a backslash: \\ \n"); // Backslash
    return 0;
}